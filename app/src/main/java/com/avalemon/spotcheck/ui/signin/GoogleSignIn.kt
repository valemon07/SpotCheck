package com.avalemon.spotcheck.ui.signin

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

sealed interface GoogleResult {
    data class Token(val idToken: String) : GoogleResult
    data object Cancelled : GoogleResult
    data class Failed(val message: String) : GoogleResult
}

/**
 * Shows the Google account picker through Credential Manager and returns an ID token for
 * Firebase. Needs an Activity context.
 *
 * The web client ID is generated by the google-services plugin as R.string.default_web_client_id
 * only after the Google provider is enabled and google-services.json is re-downloaded, so it is
 * looked up at runtime to keep the app building before that console step is done.
 */
@SuppressLint("DiscouragedApi")
suspend fun requestGoogleIdToken(activityContext: Context): GoogleResult {
    val resId = activityContext.resources.getIdentifier("default_web_client_id", "string", activityContext.packageName)
    if (resId == 0) {
        return GoogleResult.Failed("Google sign-in isn't configured yet (missing web client ID in google-services.json).")
    }
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(GetSignInWithGoogleOption.Builder(activityContext.getString(resId)).build())
        .build()
    return try {
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            GoogleResult.Token(GoogleIdTokenCredential.createFrom(credential.data).idToken)
        } else {
            GoogleResult.Failed("Unexpected credential type from Google.")
        }
    } catch (_: GetCredentialCancellationException) {
        GoogleResult.Cancelled
    } catch (_: NoCredentialException) {
        GoogleResult.Failed("No Google account available on this device. Add one in Settings and try again.")
    } catch (e: GetCredentialException) {
        GoogleResult.Failed(e.message ?: "Google sign-in failed.")
    }
}
